#include <assert.h>
#include <stdio.h>
#include <string.h>
#include <unistd.h>

#include "application/auth/usecases.h"
#include "common/db.h"
#include "common/legacy_bcrypt.h"
#include "csilk/crypto/bcrypt.h"
#include "csilk/csilk.h"
#include "csilk/drivers/db.h"
#include "csilk/drivers/db/migration.h"
#include "domain/auth/entity.h"
#include "domain/auth/repository.h"

static const char*
get_migrations_path(void)
{
    if (access("sql/migrations", F_OK) == 0) {
        return "sql/migrations";
    }
    if (access("backend/sql/migrations", F_OK) == 0) {
        return "backend/sql/migrations";
    }
    return "../sql/migrations";
}

int
main(void)
{
    printf("=== Starting Legacy Bcrypt Compatibility Unit Tests ===\n");

    const char* pwd = "LegacyPass123!";
    size_t      pwd_len = strlen(pwd);

    /* Hashes generated with csilk v0.9.0 for "LegacyPass123!" (61 chars each) */
    const char* legacy_cost4 = "$2a$04$RS9D.plUIxImPI/VjKRVsOzyL4yOAdseTQh75.YsUUY0X0peUuIWu0";
    const char* legacy_cost12 = "$2a$12$a15Md91jjNkAA5p8n2E/0.seHh6XhlxZDTuh/KIVB1xQJma/EiUxeh";

    assert(strlen(legacy_cost4) == 61);
    assert(strlen(legacy_cost12) == 61);

    /* Confirm standard csilk v1.2.0 OpenBSD verifier rejects pre-v1.2.0 61-char hashes */
    assert(csilk_bcrypt_verify(pwd, pwd_len, legacy_cost4) != 0);
    assert(csilk_bcrypt_verify(pwd, pwd_len, legacy_cost12) != 0);

    /* Legacy verifier accepts exact password on both cost=4 and cost=12 vectors */
    assert(mf_legacy_bcrypt_v090_verify(pwd, pwd_len, legacy_cost4) == 0);
    assert(mf_legacy_bcrypt_v090_verify(pwd, pwd_len, legacy_cost12) == 0);

    /* Legacy verifier rejects wrong password and invalid/non-61-char inputs */
    assert(mf_legacy_bcrypt_v090_verify("WrongPass123!", 13, legacy_cost4) != 0);
    assert(mf_legacy_bcrypt_v090_verify(NULL, 0, legacy_cost4) != 0);
    assert(mf_legacy_bcrypt_v090_verify(pwd, pwd_len, NULL) != 0);
    assert(mf_legacy_bcrypt_v090_verify(pwd, pwd_len, "") != 0);

    /* Truncated / wrong prefix / invalid base64 / out-of-range cost */
    assert(mf_legacy_bcrypt_v090_verify(
               pwd, pwd_len, "$2x$04$RS9D.plUIxImPI/VjKRVsOzyL4yOAdseTQh75.YsUUY0X0peUuIWu0") != 0);
    assert(mf_legacy_bcrypt_v090_verify(
               pwd, pwd_len, "$2a$03$RS9D.plUIxImPI/VjKRVsOzyL4yOAdseTQh75.YsUUY0X0peUuIWu0") != 0);
    assert(mf_legacy_bcrypt_v090_verify(
               pwd, pwd_len, "$2a$04$RS9D.plUIxImPI/VjKRVsOzyL4yOAdseTQh75.YsUUY0X0peUuIWu?") != 0);
    assert(mf_legacy_bcrypt_v090_verify(
               pwd, pwd_len, "$2a$04$RS9D.plUIxImPI/VjKRVsOzyL4yOAdseTQh75.YsUUY0X0peUuIWu") != 0);

    /* 61-char hash generated by csilk v1.2.0 (CSILK_BCRYPT_HASH_LEN == 62) */
    char std_hash[CSILK_BCRYPT_HASH_LEN];
    csilk_bcrypt_hash(pwd, pwd_len, 4, std_hash);
    assert(strlen(std_hash) == CSILK_BCRYPT_HASH_LEN - 1);
    assert(mf_legacy_bcrypt_v090_verify(pwd, pwd_len, std_hash) != 0);
    assert(auth_usecase_verify_and_upgrade_password(NULL, 0, pwd, pwd_len, std_hash) == 0);

    /* End-to-end DB auto-upgrade test */
    csilk_db_init();
    csilk_db_pool_t* pool = csilk_db_pool_new("sqlite", ":memory:");
    assert(pool != NULL);

    csilk_migration_engine_t* engine = NULL;
    assert(csilk_migration_engine_new(pool, get_migrations_path(), &engine) == 0 && engine != NULL);
    int applied = 0;
    assert(csilk_migration_apply(engine, &applied) == 0);
    csilk_migration_engine_free(engine);

    int64_t user_id = 0;
    assert(mf_auth_repo_create(pool, "legacy_tester", legacy_cost4, &user_id) == 0);
    assert(user_id > 0);

    /* Wrong password fails and leaves legacy hash intact */
    assert(auth_usecase_verify_and_upgrade_password(
               pool, user_id, "WrongPass123!", 13, legacy_cost4) != 0);
    mf_user_t fetched = {0};
    assert(mf_auth_repo_get_by_id(pool, user_id, &fetched) == 0);
    assert(strcmp(fetched.password_hash, legacy_cost4) == 0);

    /* Valid login verifies legacy hash and upgrades DB row to csilk v1.2.0 OpenBSD bcrypt */
    assert(auth_usecase_verify_and_upgrade_password(pool, user_id, pwd, pwd_len, legacy_cost4) ==
           0);

    memset(&fetched, 0, sizeof(fetched));
    assert(mf_auth_repo_get_by_id(pool, user_id, &fetched) == 0);
    assert(strlen(fetched.password_hash) == CSILK_BCRYPT_HASH_LEN - 1);
    assert(strcmp(fetched.password_hash, legacy_cost4) != 0);
    assert(csilk_bcrypt_verify(pwd, pwd_len, fetched.password_hash) == 0);
    assert(mf_legacy_bcrypt_v090_verify(pwd, pwd_len, fetched.password_hash) != 0);
    assert(auth_usecase_verify_and_upgrade_password(
               pool, user_id, pwd, pwd_len, fetched.password_hash) == 0);

    csilk_db_pool_free(pool);
    printf("=== Legacy Bcrypt Compatibility Unit Tests Passed! ===\n");
    return 0;
}
